import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { test } from 'node:test';
import { same, validateEvidence, orbitResult } from '../deploy/refresh_bot.mjs';

const evidence = {
  schema: 1, version: '7.25.2', channel: 'stable', platform: 'chr-x86_64',
  archiveSha256: 'a'.repeat(64), testedCommit: 'b'.repeat(40), runId: 123, runAttempt: 1,
  testedAt: '2026-11-24T11:14:06Z', passed: 72, xfailed: 9, warnings: 7, skipped: 0,
  unexpectedFailures: 0,
};
const source = { full_name: 'greenblacked/ops-toolbox' };
const run = {
  id: 123, run_attempt: 1, repository: source, head_repository: source,
  path: '.github/workflows/routeros-version.yml', head_branch: 'master',
  event: 'schedule', status: 'completed', conclusion: 'success',
  created_at: '2026-11-24T11:00:00Z', updated_at: '2026-11-24T11:15:00Z',
};
const jobs = [{ name: 'Check, test, and propose RouterOS bump', conclusion: 'success',
  steps: [{ name: 'Test candidate on RouterOS CHR', conclusion: 'success' }] }];

test('metadata timestamp churn is not a release change', () => {
  assert.ok(same({ fetchedAt: 'x', rows: [{ checkedAt: 'x', date: 'a' }] },
    { rows: [{ date: 'a', checkedAt: 'y' }], fetchedAt: 'y' }));
  assert.ok(!same({ rows: [{ date: 'a' }] }, { rows: [{ date: 'b' }] }));
  assert.ok(!same({ cves: ['CVE-1'] }, { cves: ['CVE-2'] }));
});
test('trusted CHR evidence yields WARN, never hardware PASS', () => {
  assert.ok(validateEvidence(evidence, '7.25.2', run, jobs));
  const result = orbitResult(evidence);
  assert.deepEqual(result, {
    vendor: 'mikrotik', family: 'RouterOS', build: '7.25.2', version: '7.25.2',
    stage: 'release', status: 'warn',
    checks: [
      { name: 'RouterOS CHR x86_64 candidate integration suite', status: 'pass',
        detail: '72 passed, 9 expected failures, 7 warnings, 0 skipped; no unexpected failures' },
      { name: 'Candidate archive digest pinned', status: 'pass',
        detail: 'SHA-256 ' + evidence.archiveSha256 + '; tested commit ' + evidence.testedCommit },
      { name: 'Physical hardware, Wi-Fi, RouterBOOT and deployment-specific configuration',
        status: 'untested', detail: 'Virtual CHR evidence only; no physical router validation' },
    ],
    testedAt: '2026-11-24T11:14:06Z',
    runner: 'GitHub Actions ops-toolbox run 123 attempt 1',
  });
});
test('artifact preserves canonical UTC and full decimal run identifiers', () => {
  const result = orbitResult({
    ...evidence, testedAt: '0001-01-01T00:00:00Z',
    runId: Number.MAX_SAFE_INTEGER, runAttempt: Number.MAX_SAFE_INTEGER,
  }, '7.25.2');
  assert.equal(result.testedAt, '0001-01-01T00:00:00Z');
  assert.equal(result.runner, 'GitHub Actions ops-toolbox run 9007199254740991 attempt 9007199254740991');
});
test('reject mismatched, failed, skipped or untrusted evidence', () => {
  for (const patch of [{ version: '7.25.1' }, { runAttempt: 2 }, { passed: 0 },
    { unexpectedFailures: 1 }, { archiveSha256: 'x' }, { testedAt: '2026-11-25T00:00:00Z' }]) {
    assert.equal(validateEvidence({ ...evidence, ...patch }, '7.25.2', run, jobs), false);
  }
  for (const patch of [{ path: '.github/workflows/other.yml' }, { conclusion: 'failure' },
    { event: 'pull_request' }, { head_branch: 'feature/anything' }]) {
    assert.equal(validateEvidence(evidence, '7.25.2', { ...run, ...patch }, jobs), false);
  }
  assert.equal(validateEvidence(evidence, '7.25.2', run, []), false);
});

test('reject unexpected fields, non-string identifiers and unbounded counts', () => {
  for (const patch of [
    { arbitrary: 'unexpected' },
    { archiveSha256: [evidence.archiveSha256] },
    { testedCommit: [evidence.testedCommit] },
    { warnings: 1000001 },
    { testedAt: '2026-11-31T11:14:06Z' },
    { testedAt: '0000-01-01T00:00:00Z' },
    { version: '7.25.2\n' },
  ]) {
    const invalid = { ...evidence, ...patch };
    assert.equal(validateEvidence(invalid, '7.25.2', run, jobs), false);
    assert.throws(() => orbitResult(invalid, '7.25.2'), /invalid CHR evidence schema/);
  }
  assert.throws(() => orbitResult(evidence, '7.25.3'), /invalid CHR evidence schema/);
});

test('accept schema-1 evidence generated by ops-toolbox with and without passing subtests', () => {
  const producerRun = { ...run, created_at: '2026-11-24T23:00:00Z', updated_at: '2026-11-24T23:30:00Z' };
  for (const [fixture, count] of [['no-subtests', 0], ['with-subtests', 7]]) {
    const generated = JSON.parse(readFileSync(
      new URL('./fixtures/refresh-bot/' + fixture + '.json', import.meta.url), 'utf8'));
    assert.equal(generated.subtestsPassed, count);
    assert.ok(validateEvidence(generated, '7.25.2', producerRun, jobs));
    assert.equal(orbitResult(generated, '7.25.2').status, 'warn');
  }
});

test('require a bounded integer when subtestsPassed is present', () => {
  for (const subtestsPassed of [-1, 1.5, 1000001, '0', null, undefined]) {
    const invalid = { ...evidence, subtestsPassed };
    assert.equal(validateEvidence(invalid, '7.25.2', run, jobs), false);
    assert.throws(() => orbitResult(invalid), /invalid CHR evidence schema/);
  }
  assert.ok(validateEvidence({ ...evidence, subtestsPassed: 1000000 }, '7.25.2', run, jobs));
  assert.equal(validateEvidence({ ...evidence, subtestsPassed: 0, extra: true },
    '7.25.2', run, jobs), false);
});
